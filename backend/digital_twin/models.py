"""
Data models and typed schemas for the Digital Twin State and Shadow Model.
"""

from typing import Literal, Dict, List, Optional, Tuple, Any
from pydantic import BaseModel, Field, field_validator


class TwinNodeState(BaseModel):
    """
    Virtual representation of an IoT node's current or historical state within the Digital Twin.
    Mirroring the physical/simulated telemetry stream while maintaining validation integrity.
    """
    node_id: int = Field(..., ge=0, description="Unique node identifier")
    timestamp: float = Field(..., ge=0.0, description="Telemetry epoch timestamp (simulated seconds)")
    position: Optional[Tuple[float, float]] = Field(default=None, description="Spatial coordinates (x, y) in meters")
    packet_rate: float = Field(..., ge=0.0, description="Packet generation rate (pkt/s)")
    forwarding_rate: float = Field(..., ge=0.0, description="In-transit packet forwarding rate (pkt/s)")
    packet_loss: float = Field(..., ge=0.0, le=1.0, description="Packet loss ratio [0.0, 1.0]")
    latency: float = Field(..., ge=0.0, description="End-to-end or single-hop latency in ms")
    rssi: float = Field(..., le=0.0, description="Received signal strength indicator (dBm)")
    energy: float = Field(..., ge=0.0, le=100.0, description="Remaining battery percentage [0.0, 100.0]")
    cpu: float = Field(..., ge=0.0, le=100.0, description="CPU utilization percentage [0.0, 100.0]")
    memory: float = Field(..., ge=0.0, le=100.0, description="Memory utilization percentage [0.0, 100.0]")
    neighbor_count: int = Field(..., ge=0, description="Number of 1-hop neighbors")
    connection_state: Literal["CONNECTED", "DEGRADED", "DISCONNECTED"] = Field(
        default="CONNECTED",
        description="Logical link connection state"
    )
    routing_state: Literal["IDLE", "ROUTING", "CONGESTED"] = Field(
        default="IDLE",
        description="Buffer/routing status"
    )
    threat_level: float = Field(default=0.0, ge=0.0, le=1.0, description="Threat score [0.0, 1.0]")
    trust_score: float = Field(default=1.0, ge=0.0, le=1.0, description="Trust score [0.0, 1.0]")

    def to_dict(self) -> Dict[str, Any]:
        return self.model_dump()


class LinkState(BaseModel):
    """
    Virtual representation of a wireless link between two neighboring nodes.
    Derived from mutual neighbor relationships and directional telemetry.
    """
    source_node: int = Field(..., ge=0)
    target_node: int = Field(..., ge=0)
    distance_m: Optional[float] = Field(default=None, ge=0.0)
    estimated_rssi: float = Field(..., le=0.0)
    estimated_latency: float = Field(default=0.0, ge=0.0)
    estimated_loss: float = Field(default=0.0, ge=0.0, le=1.0)
    active: bool = Field(default=True)
    last_updated: float = Field(..., ge=0.0)


class NetworkTwinState(BaseModel):
    """
    Aggregated macroscopic state of the entire network as represented in the Digital Twin.
    """
    timestamp: float = Field(..., ge=0.0)
    node_count: int = Field(..., ge=0)
    active_node_count: int = Field(..., ge=0)
    connected_node_count: int = Field(..., ge=0)
    average_packet_loss: float = Field(..., ge=0.0, le=1.0)
    average_latency: float = Field(..., ge=0.0)
    average_rssi: float = Field(..., le=0.0)
    average_cpu: float = Field(..., ge=0.0, le=100.0)
    average_memory: float = Field(..., ge=0.0, le=100.0)
    total_energy: float = Field(..., ge=0.0)
    network_availability: float = Field(..., ge=0.0, le=1.0)


class NetworkHealthSummary(BaseModel):
    """
    Descriptive summary of measurable network health conditions.
    """
    timestamp: float = Field(..., ge=0.0)
    connected_node_ratio: float = Field(..., ge=0.0, le=1.0)
    active_node_ratio: float = Field(..., ge=0.0, le=1.0)
    average_packet_loss: float = Field(..., ge=0.0, le=1.0)
    average_latency_ms: float = Field(..., ge=0.0)
    average_rssi_dbm: float = Field(..., le=0.0)
    average_energy_pct: float = Field(..., ge=0.0, le=100.0)
    degraded_node_count: int = Field(default=0, ge=0)
    disconnected_node_count: int = Field(default=0, ge=0)
    health_status: Literal["HEALTHY", "DEGRADED", "CRITICAL"] = Field(default="HEALTHY")


class SyncMetadata(BaseModel):
    """
    Metadata recording telemetry ingestion timing and synchronization latency.
    """
    telemetry_timestamp: float = Field(..., ge=0.0, description="Timestamp generated by simulated/physical node")
    ingestion_timestamp: float = Field(..., description="Wall-clock time of ingestion into Digital Twin (epoch seconds)")
    sync_latency_ms: float = Field(..., ge=0.0, description="Software ingestion processing time in milliseconds")
    node_id: int = Field(..., ge=0)
    sequence_number: int = Field(..., ge=0)
